-- Banking streamhouse demo: Db2 schema (synthetic data only).
-- Tables live in the connection's current schema. Statements are separated by ';'.
--
-- Design notes
--  * CUSTOMER and ACCOUNT are the historical "what we know" layer. Balances are
--    OPENING balances: the generator never updates them. Flink computes the current
--    balance from the opening balance plus streamed events.
--  * LAST_UPDATED lets a Kafka Connect JDBC source (timestamp mode) pick up changes.
--  * TXN_EVENT / DIGITAL_EVENT are an audit log of every generated event, including
--    the Kafka partition/offset it was published to.

CREATE TABLE CUSTOMER (
  CUSTOMER_ID               VARCHAR(20)   NOT NULL,
  NAME                      VARCHAR(100)  NOT NULL,
  SEGMENT                   VARCHAR(20)   NOT NULL,
  AVG_BALANCE               DECIMAL(18,2) NOT NULL,
  NORMAL_EXTERNAL_TRANSFER  DECIMAL(18,2) NOT NULL,
  NORMAL_CARD_TXN_PER_WEEK  INTEGER       NOT NULL,
  PRODUCTS_OWNED            INTEGER       NOT NULL,
  ENGAGEMENT_LEVEL          VARCHAR(10)   NOT NULL,
  CHURN_RISK                VARCHAR(10)   NOT NULL,
  RELATIONSHIP_MANAGER      VARCHAR(100),
  LAST_UPDATED              TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT PK_CUSTOMER PRIMARY KEY (CUSTOMER_ID),
  CONSTRAINT CK_CUSTOMER_RISK CHECK (CHURN_RISK IN ('LOW','MEDIUM','HIGH')),
  CONSTRAINT CK_CUSTOMER_ENG CHECK (ENGAGEMENT_LEVEL IN ('LOW','MEDIUM','HIGH'))
);

CREATE TABLE ACCOUNT (
  ACCOUNT_ID     VARCHAR(30)   NOT NULL,
  CUSTOMER_ID    VARCHAR(20)   NOT NULL,
  ACCOUNT_TYPE   VARCHAR(20)   NOT NULL,
  BALANCE        DECIMAL(18,2) NOT NULL,
  CURRENCY       CHAR(3)       NOT NULL DEFAULT 'IDR',
  LAST_UPDATED   TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT PK_ACCOUNT PRIMARY KEY (ACCOUNT_ID),
  CONSTRAINT FK_ACCOUNT_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER (CUSTOMER_ID),
  CONSTRAINT CK_ACCOUNT_TYPE CHECK (ACCOUNT_TYPE IN ('SAVINGS','CREDIT_CARD','MORTGAGE','INVESTMENT'))
);

CREATE TABLE SCENARIO_RUN (
  RUN_ID         VARCHAR(36)  NOT NULL,
  CUSTOMER_ID    VARCHAR(20)  NOT NULL,
  SCENARIO_NAME  VARCHAR(50)  NOT NULL,
  STATUS         VARCHAR(20)  NOT NULL,
  NEXT_STEP      INTEGER      NOT NULL DEFAULT 0,
  STARTED_AT     TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP,
  UPDATED_AT     TIMESTAMP    NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT PK_SCENARIO_RUN PRIMARY KEY (RUN_ID),
  CONSTRAINT FK_RUN_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER (CUSTOMER_ID),
  CONSTRAINT CK_RUN_STATUS CHECK (STATUS IN ('RUNNING','COMPLETED'))
);

CREATE TABLE TXN_EVENT (
  EVENT_ID          VARCHAR(36)   NOT NULL,
  RUN_ID            VARCHAR(36),
  CUSTOMER_ID       VARCHAR(20)   NOT NULL,
  ACCOUNT_ID        VARCHAR(30)   NOT NULL,
  EVENT_TIME        TIMESTAMP     NOT NULL,
  TXN_TYPE          VARCHAR(30)   NOT NULL,
  DIRECTION         VARCHAR(3)    NOT NULL,
  CHANNEL           VARCHAR(20)   NOT NULL,
  AMOUNT            DECIMAL(18,2) NOT NULL,
  CURRENCY          CHAR(3)       NOT NULL DEFAULT 'IDR',
  COUNTERPARTY_BANK VARCHAR(60),
  DESCRIPTION       VARCHAR(200),
  KAFKA_TOPIC       VARCHAR(100),
  KAFKA_PARTITION   INTEGER,
  KAFKA_OFFSET      BIGINT,
  CREATED_AT        TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT PK_TXN_EVENT PRIMARY KEY (EVENT_ID),
  CONSTRAINT FK_TXN_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER (CUSTOMER_ID),
  CONSTRAINT FK_TXN_ACCOUNT FOREIGN KEY (ACCOUNT_ID) REFERENCES ACCOUNT (ACCOUNT_ID),
  CONSTRAINT FK_TXN_RUN FOREIGN KEY (RUN_ID) REFERENCES SCENARIO_RUN (RUN_ID),
  CONSTRAINT CK_TXN_DIRECTION CHECK (DIRECTION IN ('IN','OUT')),
  CONSTRAINT CK_TXN_CHANNEL CHECK (CHANNEL IN ('INTERNAL','EXTERNAL','CARD'))
);

CREATE TABLE DIGITAL_EVENT (
  EVENT_ID        VARCHAR(36)   NOT NULL,
  RUN_ID          VARCHAR(36),
  CUSTOMER_ID     VARCHAR(20)   NOT NULL,
  EVENT_TIME      TIMESTAMP     NOT NULL,
  EVENT_TYPE      VARCHAR(30)   NOT NULL,
  CHANNEL         VARCHAR(20)   NOT NULL,
  EVENT_TEXT      VARCHAR(200),
  NUMERIC_VALUE   DECIMAL(18,2),
  KAFKA_TOPIC     VARCHAR(100),
  KAFKA_PARTITION INTEGER,
  KAFKA_OFFSET    BIGINT,
  CREATED_AT      TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT PK_DIGITAL_EVENT PRIMARY KEY (EVENT_ID),
  CONSTRAINT FK_DIG_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER (CUSTOMER_ID),
  CONSTRAINT FK_DIG_RUN FOREIGN KEY (RUN_ID) REFERENCES SCENARIO_RUN (RUN_ID)
);

CREATE TABLE AI_RECOMMENDATION (
  RECOMMENDATION_ID VARCHAR(36)   NOT NULL,
  RUN_ID            VARCHAR(36),
  CUSTOMER_ID       VARCHAR(20)   NOT NULL,
  RISK_LEVEL        VARCHAR(10)   NOT NULL,
  INPUT_STATE       VARCHAR(8000) NOT NULL,
  RECOMMENDATION    VARCHAR(8000) NOT NULL,
  SOURCE            VARCHAR(40)   NOT NULL,
  RM_DECISION       VARCHAR(20)   NOT NULL DEFAULT 'PENDING',
  DECIDED_AT        TIMESTAMP,
  CREATED_AT        TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
  CONSTRAINT PK_AI_REC PRIMARY KEY (RECOMMENDATION_ID),
  CONSTRAINT FK_AI_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER (CUSTOMER_ID),
  CONSTRAINT FK_AI_RUN FOREIGN KEY (RUN_ID) REFERENCES SCENARIO_RUN (RUN_ID),
  CONSTRAINT CK_AI_DECISION CHECK (RM_DECISION IN ('PENDING','APPROVED','DISMISSED'))
);
